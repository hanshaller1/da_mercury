// Builds a self-contained copy of the app into dist/ for hosting in a
// sandboxed page (e.g. a claude.ai artifact):
//   dist/index.html                    page content with inlined CSS
//   dist/app.js                        all UI modules bundled into one file
//   dist/worklet/reverb-processor.js   the DSP engine bundled into one file
// Usage: node tools/build-artifact.mjs

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DIST = resolve(ROOT, 'dist');

const IMPORT_RE = /import\s*\{([\s\S]*?)\}\s*from\s*['"](.+?)['"];?/g;

/** Tiny ESM bundler for this code base (named imports/exports only). */
function bundle(entry) {
  const order = [];
  const seen = new Set();
  const visit = (file) => {
    if (seen.has(file)) return;
    seen.add(file);
    const src = readFileSync(file, 'utf8');
    for (const m of src.matchAll(IMPORT_RE)) visit(resolve(dirname(file), m[2]));
    order.push(file);
  };
  visit(entry);

  const id = (file) => JSON.stringify(relative(ROOT, file));
  let out = '// generated by tools/build-artifact.mjs – do not edit\nconst __m = {};\n';
  for (const file of order) {
    let src = readFileSync(file, 'utf8');
    src = src.replace(IMPORT_RE, (_, names, from) => {
      const spec = names
        .split(',')
        .map((n) => n.trim())
        .filter(Boolean)
        .map((n) => n.replace(/\s+as\s+/, ': '))
        .join(', ');
      return `const { ${spec} } = __m[${id(resolve(dirname(file), from))}];`;
    });
    const exported = [];
    src = src.replace(/^export\s+(class|function|const|let|async function)\s+([A-Za-z_$][\w$]*)/gm, (_, kw, name) => {
      exported.push(name);
      return `${kw} ${name}`;
    });
    src = src.replace(/^export\s*\{([^}]*)\};?/gm, (_, names) => {
      exported.push(...names.split(',').map((n) => n.trim()).filter(Boolean));
      return '';
    });
    if (/^\s*(import|export)\s/m.test(src)) throw new Error('unsupported import/export in ' + file);
    out += `\n// ---- ${relative(ROOT, file)}\n__m[${id(file)}] = (() => {\n${src}\nreturn { ${exported.join(', ')} };\n})();\n`;
  }
  return out;
}

mkdirSync(resolve(DIST, 'worklet'), { recursive: true });
writeFileSync(resolve(DIST, 'worklet/reverb-processor.js'), bundle(resolve(ROOT, 'js/worklet/reverb-processor.js')));
writeFileSync(resolve(DIST, 'app.js'), bundle(resolve(ROOT, 'js/main.js')));

// page: strip document skeleton, inline the stylesheet, point to the bundle
let html = readFileSync(resolve(ROOT, 'index.html'), 'utf8');
const css = readFileSync(resolve(ROOT, 'css/style.css'), 'utf8');
const head = html.match(/<head>([\s\S]*?)<\/head>/)[1];
const body = html.match(/<body>([\s\S]*?)<\/body>/)[1];
const title = head.match(/<title>[\s\S]*?<\/title>/)[0];
const fonts = [...head.matchAll(/<link[^>]+fonts\.googleapis\.com\/css2[^>]*>/g)].map((m) => m[0]).join('\n');
const page = [
  title,
  '<meta name="dam-embed" content="1">',
  fonts,
  `<style>\n${css}\n</style>`,
  body.replace('<script type="module" src="js/main.js"></script>', '<script type="module" src="app.js"></script>').trim(),
].join('\n');
writeFileSync(resolve(DIST, 'index.html'), page + '\n');
console.log('dist/ written');
